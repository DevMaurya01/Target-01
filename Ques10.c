/*Write a program to declare different variable with types modifiers and display them.*/
#include <stdio.h>
void main()
{
    short t = 5;
    long l = 583686;
    signed s = -85;
    unsigned u = 36;
    printf("t=%d", t);
    printf("\nL=%d", l);
    printf("\nS=%d", s);
    printf("\n u=%u", u);
    return;
}