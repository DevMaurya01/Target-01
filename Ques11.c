/*write a program to change data types of results obtained by division operations.*/
#include <stdio.h>
void main()
{
    printf("\nDivision operation Result");
    printf("\nTwo Integers(5&2):%d", 5 / 2);
    printf("\nOne int & one float(5.5/2): %g", 5.5 / 2);
    printf("\nTwo Integers(5*2);%g", (float)5);
    return;
}